// Native regression check. Use a dedicated AssetFlow instance with CDP, never an active work session.
const { chromium } = require(process.env.ASSETFLOW_PLAYWRIGHT || "playwright");
const fs = require("node:fs");
const os = require("node:os");
const path = require("node:path");
const assert = require("node:assert/strict");
const { createHash } = require("node:crypto");
(async () => {
  const root = fs.mkdtempSync(path.join(os.tmpdir(), "assetflow-tools-ui-"));
  fs.writeFileSync(path.join(root, "Reference.png"), Buffer.from("iVBORw0KGgoAAAANSUhEUgAAAAgAAAAICAIAAABLbSncAAAAFUlEQVR4nGN8+PAhAzbAhFV00EoAABE4ArMNF1DjAAAAAElFTkSuQmCC", "base64"));
  fs.writeFileSync(path.join(root, "Notes & details.txt"), "Keep this source unchanged.");
  const samples = 4800, wav = Buffer.alloc(44 + samples * 2);
  wav.write("RIFF"); wav.writeUInt32LE(wav.length - 8, 4); wav.write("WAVEfmt ", 8);
  wav.writeUInt32LE(16, 16); wav.writeUInt16LE(1, 20); wav.writeUInt16LE(1, 22);
  wav.writeUInt32LE(48000, 24); wav.writeUInt32LE(96000, 28); wav.writeUInt16LE(2, 32); wav.writeUInt16LE(16, 34); wav.write("data", 36); wav.writeUInt32LE(samples * 2, 40);
  for (let i = 0; i < samples; i++) wav.writeInt16LE(Math.round(Math.sin(i / 48000 * 440 * 2 * Math.PI) * 16000), 44 + i * 2);
  fs.writeFileSync(path.join(root, "Tone.wav"), wav);
  const snapshot = () => fs.readdirSync(root).sort().map((n) => [n, createHash("sha256").update(fs.readFileSync(path.join(root, n))).digest("hex")]);
  const before = snapshot();
  const browser = await chromium.connectOverCDP(process.env.ASSETFLOW_CDP || "http://127.0.0.1:9223");
  try {
    const page = browser.contexts()[0].pages()[0];
    page.setDefaultTimeout(15000);
    const errors = []; page.on("pageerror", (e) => errors.push(e.message));
    await page.reload();
    await page.getByRole("heading", { name: "Your work, in order." }).waitFor();
    await page.waitForTimeout(300);
    await page.evaluate(async (root) => window.__TAURI_INTERNALS__.invoke("plugin:event|emit", { event: "tauri://drag-drop", payload: { paths: [root], position: { x: 400, y: 300 } } }), root);
    await page.getByRole("heading", { name: path.basename(root), exact: true }).waitFor();
    const read = (file) => page.evaluate((path) => window.__TAURI_INTERNALS__.invoke("read_technical_metadata", { path }), path.join(root, file));
    const audio = await read("Tone.wav");
    assert.ok(audio.fields.some((f) => f.label === "Sample rate" && f.value === "48.0 kHz"), JSON.stringify(audio));
    assert.ok(audio.fields.some((f) => f.label === "Audio bit depth" && f.value === "16 bit"));
    const image = await read("Reference.png");
    assert.ok(image.fields.some((f) => f.label === "Encoded dimensions" && f.value === "8 × 8 px"));
    const rejected = await page.evaluate(async (p) => { try { await window.__TAURI_INTERNALS__.invoke("read_technical_metadata", { path: p }); return false; } catch { return true; } }, path.join(root, "..", "outside.wav"));
    assert.ok(rejected, "Metadata must reject out-of-project paths");
    await page.getByRole("button", { name: "Inspect Tone.wav", exact: true }).click();
    const media = page.getByRole("dialog", { name: "Media preview" }); await media.waitFor();
    await media.getByRole("button", { name: "Open with…", exact: true }).waitFor();
    assert.equal(await media.locator(".technical-fields").count(), 0, "Extended metadata must be opt-in");
    await media.getByRole("button", { name: "Read technical metadata", exact: true }).click();
    await media.getByText("48.0 kHz", { exact: true }).waitFor();
    await page.keyboard.press("Escape");
    await page.getByRole("button", { name: "Inspect Notes & details.txt", exact: true }).click();
    await page.getByRole("dialog", { name: "Asset details" }).getByRole("button", { name: "Open with…", exact: true }).waitFor();
    await page.keyboard.press("Escape");
    await page.getByRole("textbox", { name: "Search assets" }).fill("Reference");
    await page.getByRole("button", { name: "Contact sheet", exact: true }).click();
    const sheet = page.getByRole("dialog", { name: "Contact Sheet" }); await sheet.waitFor();
    await sheet.getByRole("checkbox", { name: /^Include Reference/ }).waitFor();
    assert.equal(await sheet.getByRole("checkbox", { name: /^Include Reference/ }).count(), 1, "Export must follow filters");
    await sheet.getByRole("button", { name: "Clear selection", exact: true }).click();
    assert.ok(await sheet.getByRole("button", { name: "Export contact sheet", exact: true }).isDisabled());
    await sheet.getByRole("button", { name: "Select all 1", exact: true }).click();
    await sheet.getByRole("combobox", { name: "Contact sheet columns" }).selectOption("2");
    await sheet.getByLabel("Title", { exact: true }).fill("Studio & sample catalog");
    fs.mkdirSync("test-results", { recursive: true });
    await page.screenshot({ path: "test-results/contact-sheet.png" });
    assert.deepEqual(snapshot(), before, "Inspecting and preparing a sheet must not alter source files");
    assert.deepEqual(errors, []);
    fs.writeFileSync(path.join(os.tmpdir(), "assetflow-tools-ui.json"), JSON.stringify({ root, before }));
    console.log("Native asset-tools checks passed; contact sheet left ready for the native Save dialog check.");
  } finally { await browser.close(); }
})().catch((e) => { console.error(e); process.exitCode = 1; });
